<?php

namespace Tests\Feature\Profile;

use App\Models\User;
use Illuminate\Foundation\Testing\RefreshDatabase;
use Tests\TestCase;


class ProfileEditTest extends TestCase
{
    use RefreshDatabase;



    /**
     * プロフィール編集画面に
     * 現在のユーザー情報が初期値として表示される
     */
    public function test_profile_edit_page_displays_current_information()
    {

        /*
        |--------------------------------------------------------------------------
        | ユーザー作成
        |--------------------------------------------------------------------------
        */

        $user = User::factory()->create([

            'name' => '山田太郎',

            'profile_image' => 'profile.jpg',

            'postal_code' => '150-0001',

            'address' => '東京都渋谷区',

            'building' => '渋谷マンション',

        ]);



        /*
        |--------------------------------------------------------------------------
        | ログイン
        |--------------------------------------------------------------------------
        */

        $response = $this
            ->actingAs($user)
            ->get(
                route('profile.edit')
            );



        /*
        |--------------------------------------------------------------------------
        | 表示確認
        |--------------------------------------------------------------------------
        */

        $response->assertStatus(200);



        /*
        |--------------------------------------------------------------------------
        | 名前確認
        |--------------------------------------------------------------------------
        */

        $response->assertSee(
            '山田太郎'
        );



        /*
        |--------------------------------------------------------------------------
        | 郵便番号確認
        |--------------------------------------------------------------------------
        */

        $response->assertSee(
            '150-0001'
        );



        /*
        |--------------------------------------------------------------------------
        | 住所確認
        |--------------------------------------------------------------------------
        */

        $response->assertSee(
            '東京都渋谷区'
        );



        /*
        |--------------------------------------------------------------------------
        | 建物名確認
        |--------------------------------------------------------------------------
        */

        $response->assertSee(
            '渋谷マンション'
        );



        /*
        |--------------------------------------------------------------------------
        | プロフィール画像確認
        |--------------------------------------------------------------------------
        */

        $response->assertSee(
            'profile.jpg'
        );


    }

}