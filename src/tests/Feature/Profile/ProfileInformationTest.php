<?php

namespace Tests\Feature\Profile;

use App\Models\User;
use App\Models\Item;
use App\Models\Purchase;
use App\Models\Condition;
use Illuminate\Foundation\Testing\RefreshDatabase;
use Tests\TestCase;


class ProfileInformationTest extends TestCase
{
    use RefreshDatabase;



    /**
     * プロフィールページに
     * ユーザー情報・出品商品・購入商品が表示される
     */
    public function test_profile_information_is_displayed()
    {


        /*
        |--------------------------------------------------------------------------
        | ユーザー作成
        |--------------------------------------------------------------------------
        */


        $user = User::factory()->create([

            'name'=>'テストユーザー',

            'profile_image'=>'profile.jpg',

        ]);



        /*
        |--------------------------------------------------------------------------
        | 商品状態作成
        |--------------------------------------------------------------------------
        */


        $condition = Condition::factory()->create();



        /*
        |--------------------------------------------------------------------------
        | 出品商品作成
        |--------------------------------------------------------------------------
        */


        $sellItem = Item::factory()->create([

            'user_id'=>$user->id,

            'condition_id'=>$condition->id,

            'name'=>'出品した商品',

            'price'=>3000,

            'status'=>'selling',

        ]);



        /*
        |--------------------------------------------------------------------------
        | 購入される商品作成
        |--------------------------------------------------------------------------
        */


        $seller = User::factory()->create();


        $purchaseItem = Item::factory()->create([

            'user_id'=>$seller->id,

            'condition_id'=>$condition->id,

            'name'=>'購入した商品',

            'price'=>5000,

            'status'=>'sold',

        ]);



        /*
        |--------------------------------------------------------------------------
        | 購入履歴作成
        |--------------------------------------------------------------------------
        */


        Purchase::create([

            'user_id'=>$user->id,

            'item_id'=>$purchaseItem->id,

            'payment_method'=>'card',

            'postal_code'=>'100-0001',

            'address'=>'東京都',

            'building'=>'',

        ]);



        /*
        |--------------------------------------------------------------------------
        | ログイン
        |--------------------------------------------------------------------------
        */


        $response = $this
            ->actingAs($user)
            ->get(
                route('mypage')
            );



        /*
        |--------------------------------------------------------------------------
        | ステータス確認
        |--------------------------------------------------------------------------
        */


        $response->assertStatus(200);



        /*
        |--------------------------------------------------------------------------
        | ユーザー情報確認
        |--------------------------------------------------------------------------
        */


        $response->assertSee(
            'テストユーザー'
        );



        $response->assertSee(
            'profile.jpg'
        );



        /*
        |--------------------------------------------------------------------------
        | 出品商品確認
        |--------------------------------------------------------------------------
        */


        $response->assertSee(
            '出品した商品'
        );



        /*
        |--------------------------------------------------------------------------
        | 購入商品確認
        |--------------------------------------------------------------------------
        */


        $response->assertSee(
            '購入した商品'
        );


    }

}
